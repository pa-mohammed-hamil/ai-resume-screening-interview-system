def test_recall_at_one(
    ranking_dataset,
):
    ranked = rank_candidates(
        ranking_dataset["candidates"]
    )

    recall = recall_at_k(
        ranked,
        1,
    )

    # 1 of the 5 relevant candidates has been retrieved.
    assert recall == pytest.approx(1 / 5)


def test_recall_at_all_candidates_is_one(
    ranking_dataset,
):
    ranked = rank_candidates(
        ranking_dataset["candidates"]
    )

    recall = recall_at_k(
        ranked,
        len(ranked),
    )

    assert recall == pytest.approx(1.0)


def test_recall_does_not_decrease_as_k_increases(
    ranking_dataset,
):
    ranked = rank_candidates(
        ranking_dataset["candidates"]
    )

    recalls = [
        recall_at_k(ranked, k)
        for k in range(1, len(ranked) + 1)
    ]

    for previous, current in zip(
        recalls,
        recalls[1:],
    ):
        assert current >= previous


