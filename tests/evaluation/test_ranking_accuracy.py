# ============================================================================
# Ranking helpers
# ============================================================================

def rank_candidates(candidates):
    """Reference ranking implementation."""

    return sorted(
        candidates,
        key=lambda candidate: candidate["score"],
        reverse=True,
    )


def precision_at_k(
    ranked_candidates,
    k: int,
    relevance_threshold: int = 1,
) -> float:
    """Calculate Precision@K."""

    if k <= 0:
        raise ValueError("k must be greater than zero.")

    if not ranked_candidates:
        return 0.0

    top_k = ranked_candidates[:k]

    relevant = sum(
        candidate["relevance"] >= relevance_threshold
        for candidate in top_k
    )

    return relevant / len(top_k)


def recall_at_k(
    ranked_candidates,
    k: int,
    relevance_threshold: int = 1,
) -> float:
    """Calculate Recall@K."""

    if k <= 0:
        raise ValueError("k must be greater than zero.")

    if not ranked_candidates:
        return 0.0

    total_relevant = sum(
        candidate["relevance"] >= relevance_threshold
        for candidate in ranked_candidates
    )

    if total_relevant == 0:
        return 0.0

    top_k = ranked_candidates[:k]

    retrieved_relevant = sum(
        candidate["relevance"] >= relevance_threshold
        for candidate in top_k
    )

    return retrieved_relevant / total_relevant


def reciprocal_rank(
    ranked_candidates,
    relevance_threshold: int = 1,
) -> float:
    """Calculate Mean Reciprocal Rank for one query."""

    for index, candidate in enumerate(ranked_candidates, start=1):
        if candidate["relevance"] >= relevance_threshold:
            return 1.0 / index

    return 0.0


def dcg_at_k(
    ranked_candidates,
    k: int,
) -> float:
    """Calculate Discounted Cumulative Gain@K."""

    score = 0.0

    for index, candidate in enumerate(ranked_candidates[:k], start=1):
        relevance = candidate["relevance"]

        score += (
            (2**relevance - 1)
            / math.log2(index + 1)
        )

    return score


def ndcg_at_k(
    ranked_candidates,
    k: int,
) -> float:
    """Calculate normalized DCG@K."""

    if not ranked_candidates:
        return 0.0

    actual_dcg = dcg_at_k(
        ranked_candidates,
        k,
    )

    ideal_candidates = sorted(
        ranked_candidates,
        key=lambda candidate: candidate["relevance"],
        reverse=True,
    )

    ideal_dcg = dcg_at_k(
        ideal_candidates,
        k,
    )

    if ideal_dcg == 0:
        return 0.0

    return actual_dcg / ideal_dcg


