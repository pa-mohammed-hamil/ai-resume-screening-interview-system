def test_highly_relevant_candidates_are_prioritized(
    ranking_dataset,
):
    ranked = rank_candidates(
        ranking_dataset["candidates"]
    )

    top_two = ranked[:2]

    assert all(
        candidate["relevance"] == 3
        for candidate in top_two
    )


def test_non_relevant_candidates_are_not_in_top_three(
    ranking_dataset,
):
    ranked = rank_candidates(
        ranking_dataset["candidates"]
    )

    top_three = ranked[:3]

    assert all(
        candidate["relevance"] > 0
        for candidate in top_three
    )


def test_relevance_is_generally_monotonic(
    ranking_dataset,
):
    ranked = rank_candidates(
        ranking_dataset["candidates"]
    )

    relevance = [
        candidate["relevance"]
        for candidate in ranked
    ]

    # The synthetic model should never place a zero-relevance candidate
    # above a relevant candidate.
    first_zero = next(
        (
            index
            for index, value in enumerate(relevance)
            if value == 0
        ),
        len(relevance),
    )

    assert all(
        value > 0
        for value in relevance[:first_zero]
    )


