def test_improving_candidate_score_cannot_lower_rank():
    candidates = [
        {
            "id": "candidate-a",
            "score": 0.70,
            "relevance": 1,
        },
        {
            "id": "candidate-b",
            "score": 0.80,
            "relevance": 2,
        },
    ]

    initial = rank_candidates(candidates)

    assert initial[0]["id"] == "candidate-b"

    candidates[0]["score"] = 0.90

    updated = rank_candidates(candidates)

    assert updated[0]["id"] == "candidate-a"


def test_decreasing_candidate_score_cannot_improve_rank():
    candidates = [
        {
            "id": "candidate-a",
            "score": 0.90,
            "relevance": 2,
        },
        {
            "id": "candidate-b",
            "score": 0.80,
            "relevance": 1,
        },
    ]

    initial = rank_candidates(candidates)

    assert initial[0]["id"] == "candidate-a"

    candidates[0]["score"] = 0.50

    updated = rank_candidates(candidates)

    assert updated[0]["id"] == "candidate-b"


