# ============================================================================
# Pairwise ranking accuracy
# ============================================================================

def pairwise_accuracy(ranked_candidates):
    """
    Measure whether pairs are ordered according to relevance.

    Equal-relevance pairs are ignored.
    """

    total = 0
    correct = 0

    for i in range(len(ranked_candidates)):
        for j in range(i + 1, len(ranked_candidates)):
            first = ranked_candidates[i]
            second = ranked_candidates[j]

            if first["relevance"] == second["relevance"]:
                continue

            total += 1

            if first["relevance"] > second["relevance"]:
                correct += 1

    if total == 0:
        return 0.0

    return correct / total


def test_pairwise_ranking_accuracy_is_high(
    ranking_dataset,
):
    ranked = rank_candidates(
        ranking_dataset["candidates"]
    )

    accuracy = pairwise_accuracy(ranked)

    assert accuracy >= 0.80


