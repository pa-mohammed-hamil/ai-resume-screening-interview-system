def test_candidates_are_sorted_by_score_descending(
    ranking_dataset,
):
    candidates = ranking_dataset["candidates"]

    ranked = rank_candidates(candidates)

    scores = [
        candidate["score"]
        for candidate in ranked
    ]

    assert scores == sorted(
        scores,
        reverse=True,
    )


