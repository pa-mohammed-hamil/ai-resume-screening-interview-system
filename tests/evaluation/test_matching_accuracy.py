def calculate_match_score(resume, job):
    """
    Reference overall matching calculation.

    Production implementation can replace this with:
        ResumeJobMatcher.match()
    """

    skill_score = keyword_match_score(
        resume["skills"],
        job["required_skills"],
    )

    role_score = (
        1.0
        if normalize_skill(resume["role"])
        == normalize_skill(job["role"])
        else 0.0
    )

    # Required skills are deliberately weighted more heavily.
    return (
        skill_score * 0.8
        + role_score * 0.2
    )


@pytest.mark.parametrize(
    "resume_skills, job_skills, expected_minimum",
    [
        (
            ["Python", "FastAPI", "PostgreSQL"],
            ["Python", "FastAPI", "PostgreSQL"],
            0.8,
        ),
        (
            ["Python", "FastAPI"],
            ["Python", "FastAPI", "PostgreSQL"],
            0.5,
        ),
        (
            ["React", "JavaScript"],
            ["Python", "FastAPI", "PostgreSQL"],
            0.0,
        ),
    ],
)
def test_overall_match_score(
    resume_skills,
    job_skills,
    expected_minimum,
):
    resume = {
        "skills": resume_skills,
        "role": "Backend Developer",
    }

    job = {
        "required_skills": job_skills,
        "role": "Backend Developer",
    }

    score = calculate_match_score(resume, job)

    assert score >= expected_minimum
    assert 0.0 <= score <= 1.0


