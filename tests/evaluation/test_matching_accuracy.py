def test_identical_vectors_have_similarity_of_one():
    vector = [0.2, 0.5, 0.8, 0.3]

    similarity = cosine_similarity(vector, vector)

    assert similarity == pytest.approx(1.0)


def test_orthogonal_vectors_have_similarity_of_zero():
    vector_a = [1.0, 0.0]
    vector_b = [0.0, 1.0]

    similarity = cosine_similarity(vector_a, vector_b)

    assert similarity == pytest.approx(0.0)


def test_semantically_similar_vectors_score_higher():
    resume_vector = [0.9, 0.8, 0.7]
    related_job_vector = [0.85, 0.75, 0.65]
    unrelated_job_vector = [0.0, 0.1, 0.9]

    related_score = cosine_similarity(
        resume_vector,
        related_job_vector,
    )

    unrelated_score = cosine_similarity(
        resume_vector,
        unrelated_job_vector,
    )

    assert related_score > unrelated_score


