def normalize_skill(skill: str) -> str:
    """Normalize a skill for deterministic comparison."""

    return (
        skill.lower()
        .strip()
        .replace("-", " ")
        .replace("_", " ")
    )


def keyword_match_score(
    resume_skills: list[str],
    required_skills: list[str],
) -> float:
    """
    Calculate required-skill coverage.

    This reference implementation is intentionally simple. Replace it with
    the real KeywordMatcher once that module is implemented.
    """

    if not required_skills:
        return 0.0

    resume = {
        normalize_skill(skill)
        for skill in resume_skills
    }

    required = {
        normalize_skill(skill)
        for skill in required_skills
    }

    matched = resume.intersection(required)

    return len(matched) / len(required)


def cosine_similarity(vector_a, vector_b) -> float:
    """Small reference implementation for semantic similarity."""

    dot_product = sum(a * b for a, b in zip(vector_a, vector_b))

    magnitude_a = math.sqrt(sum(a * a for a in vector_a))
    magnitude_b = math.sqrt(sum(b * b for b in vector_b))

    if magnitude_a == 0 or magnitude_b == 0:
        return 0.0

    return dot_product / (magnitude_a * magnitude_b)


