def test_known_matches_score_higher_than_non_matches(
    evaluation_dataset,
):
    matched_scores = []
    unmatched_scores = []

    for item in evaluation_dataset:
        score = calculate_match_score(
            item["resume"],
            item["job"],
        )

        if item["expected_match"] == 1.0:
            matched_scores.append(score)
        else:
            unmatched_scores.append(score)

    assert sum(matched_scores) / len(matched_scores) > (
        sum(unmatched_scores) / len(unmatched_scores)
    )


def test_matching_accuracy_above_minimum_threshold(
    evaluation_dataset,
):
    predictions = []

    for item in evaluation_dataset:
        score = calculate_match_score(
            item["resume"],
            item["job"],
        )

        prediction = 1.0 if score >= 0.5 else 0.0

        predictions.append(
            prediction == item["expected_match"]
        )

    accuracy = sum(predictions) / len(predictions)

    # Small synthetic dataset: this is a smoke/evaluation test,
    # not a statistically meaningful benchmark.
    assert accuracy >= 0.75


